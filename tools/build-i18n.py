"""Build i18n-dict.js from translations.txt and validate it.

Usage: python3 tools/build-i18n.py [audit-keys.json]
Checks every translation keeps the same {n} placeholders and closing tags as its English key.
If an audit file (list of keys the app actually shows) is given, also reports missing and unused keys.
"""
import json, re, sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
entries, cur, errors = {}, {}, []

for line in (root / 'translations.txt').read_text(encoding='utf-8').splitlines():
    if line.startswith('#') or not line.strip():
        continue
    tag, _, text = line.partition(': ')
    if tag == 'K':
        cur = {'K': text}
    elif tag in ('S', 'T'):
        cur[tag] = text
        if tag == 'T':
            if cur['K'] in entries:
                errors.append(f'duplicate key: {cur["K"]}')
            entries[cur['K']] = (cur.get('S', ''), cur['T'])
    else:
        errors.append(f'bad line: {line[:60]}')

ph = lambda s: sorted(re.findall(r'\{\d+\}', s))
closers = lambda s: sorted(re.findall(r'</[a-z]+>', s))
for k, (si, ta) in entries.items():
    for name, t in (('si', si), ('ta', ta)):
        if not t:
            errors.append(f'[{name}] empty: {k}')
        if ph(t) != ph(k):
            errors.append(f'[{name}] placeholders differ: {k}')
        if closers(t) != closers(k):
            errors.append(f'[{name}] closing tags differ: {k}')

if len(sys.argv) > 1:
    audit = set(json.load(open(sys.argv[1], encoding='utf-8')))
    missing = sorted(audit - set(entries), key=len)
    unused = sorted(set(entries) - audit, key=len)
    print(f'audit: {len(audit)} keys, {len(missing)} missing, {len(unused)} not seen in audit (states the audit did not reach)')
    for m in missing:
        print('  MISSING', m)

dict_js = {'si': {k: v[0] for k, v in entries.items()}, 'ta': {k: v[1] for k, v in entries.items()}}
(root / 'i18n-dict.js').write_text(
    '/* Generated by tools/build-i18n.py from translations.txt. Edit translations.txt, not this file. */\n'
    'window.I18N_DICT = ' + json.dumps(dict_js, ensure_ascii=False, indent=1) + ';\n', encoding='utf-8')

print(f'{len(entries)} entries written to i18n-dict.js')
for e in errors:
    print('  ERROR', e)
sys.exit(1 if errors else 0)
